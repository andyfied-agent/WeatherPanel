def main():
    parser = argparse.ArgumentParser(
        description='Weather Panel Configuration Manager'
    )
    parser.add_argument(
        '--config', '-c',
        help='Path to configuration file'
    )
    parser.add_argument(
        '--output', '-o',
        help='Output directory for generated files'
    )
    parser.add_argument(
        '--validate', '-v',
        action='store_true',
        help='Validate configuration'
    )
    parser.add_argument(
        '--generate-config',
        action='store_true',
        help='Generate board_config.json'
    )
    parser.add_argument(
        '--generate-h',
        action='store_true',
        help='Generate Config.h'
    )
    parser.add_argument(
        '--ssid',
        help='WiFi SSID'
    )
    parser.add_argument(
        '--password',
        help='WiFi password'
    )
    parser.add_argument(
        '--timezone',
        type=int,
        default=8,
        help='Timezone offset in hours (default: 8)'
    )

    args = parser.parse_args()

    # Load configuration
    config = load_config(args.config)

    # Update from command line arguments
    if args.ssid:
        config['network']['ssid'] = args.ssid
    if args.password:
        config['network']['password'] = args.password
    config['network']['gmt_offset_hours'] = args.timezone

    # Validate if requested
    if args.validate:
        errors = validate_config(config)
        if errors:
            print("Configuration errors:")
            for error in errors:
                print(f"  - {error}")
            return 1
        else:
            print("Configuration is valid!")
            return 0

    # Generate files if requested
    output_dir = Path(args.output) if args.output else Path(__file__).parent
    output_dir.mkdir(parents=True, exist_ok=True)

    if args.generate_config:
        config_path = output_dir / 'board_config.json'
        save_config(config, config_path)
        print(f"Generated: {config_path}")

    if args.generate_h:
        config_h_path = output_dir / 'Config.h'
        generate_config_h(config, config_h_path)
        print(f"Generated: {config_h_path}")

    # Generate both by default if neither specified
    if not args.generate_config and not args.generate_h and not args.validate:
        save_config(config, output_dir / 'board_config.json')
        generate_config_h(config, output_dir / 'Config.h')
        print(f"Generated configuration files in: {output_dir}")

    return 0

if __name__ == '__main__':
    exit(main())
