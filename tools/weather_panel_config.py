def load_config(config_path=None):
    """Load configuration from file or use defaults"""
    if config_path and Path(config_path).exists():
        with open(config_path, 'r') as f:
            return json.load(f)
    return DEFAULT_CONFIG.copy()

def save_config(config, output_path):
    """Save configuration to file"""
    with open(output_path, 'w') as f:
        json.dump(config, f, indent=2)

def validate_config(config):
    """Validate configuration for correctness"""
    errors = []

    # Check board configuration
    if config.get('board', {}).get('fqbn') != 'esp32:esp32:esp32s3':
        errors.append("Board FQBN should be esp32:esp32:esp32s3 for ESP32-S3-Touch-LCD-3.49")

    # Check display resolution
    display = config.get('display', {})
    if display.get('resolution', {}).get('width') != 172:
        errors.append("Display width should be 172 for AXS15231B")
    if display.get('resolution', {}).get('height') != 640:
        errors.append("Display height should be 640 for AXS15231B")

    # Check QSPI pins
    qspi = config.get('qspi_pins', {})
    required_qspi = ['cs', 'sck', 'd0', 'd1', 'd2', 'd3']
    for pin in required_qspi:
        if pin not in qspi:
            errors.append(f"QSPI pin '{pin}' is missing")

    # Check network settings
    network = config.get('network', {})
    if not network.get('ssid'):
        errors.append("WiFi SSID is not configured")
    if not network.get('password'):
        errors.append("WiFi password is not configured")

    return errors

